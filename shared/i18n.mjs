/** Translates UI text only. Scene names and task titles must remain outside this boundary. */
export function translate(language,value) {
  if(language !== 'en' || typeof value !== 'string' || !/[\u3400-\u9fff]/.test(value)) return value;
  if(Object.hasOwn(messages,value)) return messages[value];
  for(const {regex,value:target,indices} of patterns) {
    const match=regex.exec(value);
    if(match) return target.replace(/\{(\d+)\}/g,(_,i)=>match[indices.indexOf(Number(i))+1] ?? '');
  }
  for(const [prefix,target] of prefixes) if(value.startsWith(prefix)) return target+value.slice(prefix.length);
  return value;
}
